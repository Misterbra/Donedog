const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('taskdog', {
  storageStatus: () => ipcRenderer.invoke('storage:status'),
  retryStorage: () => ipcRenderer.invoke('storage:retry'),
  onStorageStatus: (cb) => ipcRenderer.on('storage:status', (_e, status) => cb(status)),
  loadTasks: () => ipcRenderer.invoke('tasks:load'),
  saveTasks: (tasks) => ipcRenderer.send('tasks:save', tasks),
  loadMissions: () => ipcRenderer.invoke('missions:load'),
  saveMissions: (data) => ipcRenderer.send('missions:save', data),
  idleSeconds: () => ipcRenderer.invoke('sys:idleSeconds'),
  exportMissionsCsv: (csv, name) => ipcRenderer.invoke('missions:exportCsv', csv, name),
  loadSettings: () => ipcRenderer.invoke('settings:load'),
  saveSettings: (s) => ipcRenderer.send('settings:save', s),
  getVersion: () => ipcRenderer.invoke('app:version'),
  setLanguage: (language) => ipcRenderer.invoke('settings:language', language),
  listSounds: () => ipcRenderer.invoke('sounds:list'),
  setIgnoreMouse: (ignore) => ipcRenderer.send('mouse:ignore', ignore),
  blurWindow: () => ipcRenderer.send('window:blur'),
  quit: () => ipcRenderer.send('app:quit'),
  tidyDesktop: () => ipcRenderer.invoke('desktop:tidy'),
  untidyDesktop: () => ipcRenderer.invoke('desktop:untidy'),
  sysInfo: () => ipcRenderer.invoke('sys:info'),
  ttsSpeak: (text) => ipcRenderer.invoke('tts:speak', text),
  getHead: () => ipcRenderer.invoke('head:get'),
  pickHead: () => ipcRenderer.invoke('head:pick'),
  clearHead: () => ipcRenderer.invoke('head:clear'),
  onSpeakTasks: (cb) => ipcRenderer.on('speak-tasks', cb),
  onPlatforms: (cb) => ipcRenderer.on('platforms', (e, d) => cb(d)),
  onApps: (cb) => ipcRenderer.on('apps', (e, d) => cb(d)),
  onIcons: (cb) => ipcRenderer.on('icons', (e, d) => cb(d)),
  onTidyStep: (cb) => ipcRenderer.on('tidy:step', (e, d) => cb(d)),
  onTidyDone: (cb) => ipcRenderer.on('tidy:done', (e, d) => cb(d)),
  onTidyAsk: (cb) => ipcRenderer.on('tidy:ask', cb),
  onHead: (cb) => ipcRenderer.on('head', (e, d) => cb(d)),
  onMuted: (cb) => ipcRenderer.on('muted:set', (e, d) => cb(d)),
  onSkin: (cb) => ipcRenderer.on('skin:set', (e, d) => cb(d)),
  onLanguage: (cb) => ipcRenderer.on('language:set', (e, d) => cb(d)),
  onOpenPanel: (cb) => ipcRenderer.on('panel:open', (e, d) => cb(d))
});
